"""
Generates the replay traces used by the acceptance matrix.

The traces are plain CSV (time_ms, pressure_Pa, temperature_C) and a companion
C++ header so the firmware can embed them without a filesystem. Both are
committed; rerun this script after changing a profile.

Pressure comes from the inverse of the documented altitude model:

    P = P0 * (1 - h / 44330) ** (1 / 0.1903)

with P0 taken from the bench.
"""

import math
import pathlib

P0 = 95120.0          # bench pressure, Pa
T0 = 21.5             # bench temperature, C
STEP_MS = 50


def pressure(height_m, p0=P0):
    ratio = 1.0 - height_m / 44330.0
    if ratio <= 0.0:
        raise ValueError("height outside the model")
    return p0 * ratio ** (1.0 / 0.1903)


def profile(points):
    """points: [(time_ms, height_m)] -> interpolated samples every 50 ms."""
    out = []
    t_end = points[-1][0]
    t = 0
    i = 0
    while t <= t_end:
        while i + 1 < len(points) and points[i + 1][0] < t:
            i += 1
        t0, h0 = points[i]
        t1, h1 = points[min(i + 1, len(points) - 1)]
        if t1 == t0:
            h = h1
        else:
            f = (t - t0) / (t1 - t0)
            h = h0 + f * (h1 - h0)
        out.append((t, h))
        t += STEP_MS
    return out


def temperature(steps, default=T0):
    """steps: [(time_ms, temp_C)] -> list aligned with the samples later."""
    def at(t):
        value = default
        for when, temp in steps:
            if t >= when:
                value = temp
        return value
    return at


TRACES = {
    # AT-04a: descending, but never above the 1.5 m minimum.
    "at04a": {
        "points": [(0, 0.0), (2000, 0.0), (5000, -0.8), (8000, -1.2)],
        "temp": [],
        "note": "stays below the minimum: no deployment",
    },
    # AT-04b: above the minimum, but ascending and then holding.
    "at04b": {
        "points": [(0, 0.0), (2000, 0.0), (6000, 4.0), (9000, 4.0)],
        "temp": [],
        "note": "above the minimum but not descending: no deployment",
    },
    # AT-05 / AT-06: baseline, ascent, peak, sustained descent.
    "at05": {
        "points": [(0, 0.0), (2000, 0.0), (5000, 6.0), (5300, 6.0),
                   (9000, -1.4), (19000, -9.4)],
        "temp": [],
        "note": "one deployment ~0.4 s after the peak, then no retrigger",
    },
    # at08: deployment, heat starts 2 s later, cools 5 s after that.
    "at08": {
        "points": [(0, 0.0), (2000, 0.0), (5000, 6.0), (5300, 6.0),
                   (9000, -1.4), (19000, -9.4)],
        "temp": [(0, T0), (7300, 32.0), (11000, 24.0)],
        "note": "ON, blink from ~2 s after deploy, steady for the remainder",
    },
    # at09: heat starts late, after the 10 s deployment deadline.
    "at09": {
        "points": [(0, 0.0), (2000, 0.0), (5000, 6.0), (5300, 6.0),
                   (9000, -1.4), (22000, -12.4)],
        "temp": [(0, T0), (17500, 32.0), (22500, 24.0)],
        "note": "blink overrides an expired deployment: no steady ON afterwards",
    },
    # at07a: heat only, one complete 5 s window, then cooling.
    "at07a": {
        "points": [(0, 0.0), (9000, 0.0)],
        "temp": [(0, T0), (4000, 32.0), (9000, 24.0)],
        "note": "blink for 5 s, then off: no deployment involved",
    },
    # at07b: heat persists past the first window, cools early in the renewal.
    "at07b": {
        "points": [(0, 0.0), (16000, 0.0)],
        "temp": [(0, T0), (4000, 32.0), (14000, 24.0)],
        "note": "two renewals while hot, then cooling clears it",
    },}


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    out_dir = root / "traces"
    out_dir.mkdir(exist_ok=True)

    header = [
        "/* Generated by tools/make-traces.py - do not edit by hand. */",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "struct TraceSample {",
        "\tuint32_t time_ms;",
        "\tint32_t pressure_pa;",
        "\tint16_t temperature_c_x100;",
        "};",
        "",
        "struct Trace {",
        "\tconst char *name;",
        "\tconst char *note;",
        "\tconst TraceSample *samples;",
        "\tunsigned int count;",
        "};",
        "",
    ]

    table = []

    for name, spec in TRACES.items():
        samples = profile(spec["points"])
        temp_at = temperature(spec["temp"])

        rows = []
        for t, h in samples:
            p = pressure(h)
            rows.append((t, round(p), round(temp_at(t) * 100)))

        csv_path = out_dir / f"{name}.csv"
        with csv_path.open("w", newline="\n") as handle:
            handle.write("time_ms,pressure_Pa,temperature_C\n")
            for t, p, tc in rows:
                handle.write(f"{t},{p},{tc / 100:.2f}\n")

        header.append(f"/* {name}: {spec['note']} */")
        header.append(f"static const TraceSample k{name}[] = {{")
        for t, p, tc in rows:
            header.append(f"\t{{{t}, {p}, {tc}}},")
        header.append("};")
        header.append("")

        table.append((name, spec["note"], f"k{name}", len(rows)))

    header.append("static const Trace kTraces[] = {")
    for name, note, symbol, count in table:
        header.append(f'\t{{"{name}", "{note}", {symbol}, {count}}},')
    header.append("};")
    header.append("")
    header.append("constexpr unsigned int kTraceCount =")
    header.append("\tsizeof(kTraces) / sizeof(kTraces[0]);")
    header.append("")

    (root / "src" / "traces_data.hpp").write_text("\n".join(header), newline="\n")

    for name, note, _, count in table:
        print(f"{name:6} {count:4} samples  {note}")


if __name__ == "__main__":
    main()
